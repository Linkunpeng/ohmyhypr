def idle_config(cfg: dict[str, Any]) -> str:
    options = cfg.get("lock", {})
    timeout = options.get("timeout_seconds", 600)
    if isinstance(timeout, bool) or not isinstance(timeout, int) or timeout < 0:
        raise LockError("lock.timeout_seconds must be a non-negative integer")
    before_sleep = options.get("before_sleep", True)
    if not isinstance(before_sleep, bool):
        raise LockError("lock.before_sleep must be true or false")
    command = shlex.quote(str(paths.REPO / "bin/omh")) + " lock"
    before = "    before_sleep_cmd = loginctl lock-session\n    inhibit_sleep = 3\n" if before_sleep else ""
    if timeout:
        listener = f"\nlistener {{\n    timeout = {timeout}\n    on-timeout = loginctl lock-session\n}}\n"
    else:
        # hypridle warns when no listeners exist, even when only sleep locking is wanted.
        listener = "\n# No-op listener: idle locking is disabled.\nlistener {\n    timeout = 2147483\n    on-timeout = true\n}\n"
    return f"# Generated by ohmyhypr\ngeneral {{\n    lock_cmd = {command}\n{before}}}\n{listener}"


def lock() -> None:
    paths.RUNTIME.mkdir(parents=True, exist_ok=True)
    fd = os.open(paths.RUNTIME / "hyprlock.lock", os.O_CREAT | os.O_RDWR, 0o600)
    try:
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            os.close(fd)
            return
        theme._write_atomic(paths.LOCK_CONFIG, lock_config())
        os.set_inheritable(fd, True)
        os.execvp("hyprlock", ["hyprlock", "--no-fade-in", "--config", str(paths.LOCK_CONFIG)])
    finally:
        # On successful exec the inheritable descriptor stays open until hyprlock exits.
        try:
            os.close(fd)
        except OSError:
            pass


def idle(cfg: dict[str, Any]) -> None:
    config = idle_config(cfg)
    theme._write_atomic(paths.IDLE_CONFIG, config)
    os.execvp("hypridle", ["hypridle", "--config", str(paths.IDLE_CONFIG)])
